package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

func writeReport(root string, results []Result) string {
	path := filepath.Join(root, "docs", "generated-fixtures.md")
	_ = os.MkdirAll(filepath.Dir(path), 0o755)

	var builder strings.Builder
	summary := summarize(results)
	builder.WriteString("# Generated IO fixtures\n\n")
	builder.WriteString("Generated by `internal/genfixtures` on " + time.Now().Format("2006-01-02") + ".\n\n")
	builder.WriteString("The generator seeds from the existing `test/` pairs, mutates them, runs each Go solution with coverage instrumentation, and keeps inputs that reach new blocks. The expected output is the Go solution's stdout.\n\n")
	builder.WriteString("This is best-effort. It does **not** know the original Coursera constraints, so a generated input can be semantically invalid. As a safety net, a candidate must stay inside the token/line-count and numeric-domain envelope of the existing seeds, have deterministic output, and not rely on an ignored trailing token. Problems whose seed inputs are all empty are skipped.\n\n")
	builder.WriteString("The sibling Python solution is run as a secondary check. Its failure or disagreement is recorded as a warning but does **not** block a fixture; Go is the oracle. Use `-python-veto` to restore the old blocking behavior.\n\n")
	builder.WriteString("For problems with multiple valid outputs or floating-point answers, `.a` matches this Go implementation, not necessarily every correct implementation.\n\n")
	builder.WriteString("Coverage is measured only on functions reachable from `main`. I/O error-handling branches such as `if err != nil { return }` after `fmt.Fscan` are excluded from the target percentage.\n\n")
	builder.WriteString("Regenerate with:\n\n```sh\ngo run ./internal/genfixtures -write\n```\n\n")
	builder.WriteString("Use `-only <regexp>` to limit the run and `-max-new`, `-rounds`, `-batch` to tune effort.\n\n")

	builder.WriteString("## Summary\n\n")
	builder.WriteString(fmt.Sprintf("- Problems: %d\n", len(results)))
	builder.WriteString(fmt.Sprintf("- New fixtures: %d\n", summary.Generated))
	builder.WriteString(fmt.Sprintf("- Full reachable target covered: %d\n", summary.OK))
	builder.WriteString(fmt.Sprintf("- Partial: %d\n", summary.Partial))
	builder.WriteString(fmt.Sprintf("- Already covered by existing fixtures: %d\n", summary.Already))
	builder.WriteString(fmt.Sprintf("- No new coverage found: %d\n", summary.NoNew))
	builder.WriteString(fmt.Sprintf("- Skipped (no seed fixtures): %d\n", summary.NoSeed))
	builder.WriteString(fmt.Sprintf("- Skipped (all seed inputs empty): %d\n", summary.Weak))
	builder.WriteString(fmt.Sprintf("- Other failures: %d\n\n", summary.Other))

	builder.WriteString("## Problems\n\n")
	builder.WriteString("| Problem | Seeds | New | Raw coverage | Target coverage | Status | Notes |\n")
	builder.WriteString("|---|---:|---:|---:|---:|---|---|\n")

	sorted := append([]Result(nil), results...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Rel < sorted[j].Rel })
	for _, result := range sorted {
		raw := "-"
		target := "-"
		if result.TargetBlocks > 0 || result.TargetAfter > 0 {
			raw = fmt.Sprintf("%.1f%% → %.1f%%", result.RawBefore, result.RawAfter)
			target = fmt.Sprintf("%.1f%% → %.1f%%", result.TargetBefore, result.TargetAfter)
		}
		notes := reportNotes(result)
		builder.WriteString(fmt.Sprintf("| `%s` | %d | %d | %s | %s | %s | %s |\n",
			result.Rel, result.Existing, result.Generated, raw, target, result.Status, notes))
	}

	var partials []Result
	for _, result := range sorted {
		if len(result.Uncovered) > 0 {
			partials = append(partials, result)
		}
	}
	if len(partials) > 0 {
		builder.WriteString("\n## Residual reachable blocks\n\n")
		builder.WriteString("Blocks below stayed uncovered after the mutation budget. Some may need inputs outside the seeded format; inspect the source before adding more fixtures.\n\n")
		for _, result := range partials {
			builder.WriteString("### `" + result.Rel + "`\n\n")
			limit := len(result.Uncovered)
			if limit > 12 {
				limit = 12
			}
			for _, block := range result.Uncovered[:limit] {
				builder.WriteString(fmt.Sprintf("- `%s`\n", block.String()))
			}
			if len(result.Uncovered) > limit {
				builder.WriteString(fmt.Sprintf("- … %d more\n", len(result.Uncovered)-limit))
			}
			builder.WriteString("\n")
		}
	}

	builder.WriteString("\n## Caveats\n\n")
	builder.WriteString("- Mutations can break the original input grammar. A fixture only requires exit status 0, so semantic validity is not guaranteed.\n")
	builder.WriteString("- Problems with several valid answers (topological order, Eulerian cycle, LP, genome assembly) may produce implementation-specific `.a` files.\n")
	builder.WriteString("- Floating-point outputs are stored verbatim; compare them with a tolerance when reimplementing.\n")
	builder.WriteString("- The Python cross-check is warning-only by default. A mismatch can mean a non-unique answer, an invalid input, or a Python bug. Pass `-python-veto` to make it block candidates.\n")

	if err := os.WriteFile(path, []byte(builder.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write report: %v\n", err)
	}
	return path
}

func reportNotes(result Result) string {
	var parts []string
	if len(result.GeneratedFiles) > 0 {
		names := result.GeneratedFiles
		if len(names) > 5 {
			names = names[:5]
		}
		parts = append(parts, "fixtures: "+strings.Join(names, ", "))
	}
	if result.BuildErr != "" {
		parts = append(parts, "build: "+oneLine(result.BuildErr))
	}
	for _, warning := range result.Warnings {
		parts = append(parts, oneLine(warning))
		if len(parts) >= 4 {
			break
		}
	}
	if len(result.Uncovered) > 0 {
		parts = append(parts, fmt.Sprintf("left %d blocks", len(result.Uncovered)))
	}
	return escapeTable(strings.Join(parts, "; "))
}

func oneLine(value string) string {
	value = strings.ReplaceAll(value, "\n", " ")
	value = strings.ReplaceAll(value, "\r", " ")
	if len(value) > 120 {
		value = value[:117] + "..."
	}
	return value
}

func escapeTable(value string) string {
	return strings.ReplaceAll(value, "|", "\\|")
}
